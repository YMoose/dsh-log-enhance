import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { copyFileSync, cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Regression cover for `verify --types-root` (design.md 2.5 offline core):
 * redirect the @deepseek-ai/dsh-* type resolution anchor from the upward
 * node_modules search to an explicit directory, without touching anything
 * else (cordis and friends still resolve locally).
 *
 * The money assertion is the drift case: the SAME repository with the SAME
 * committed coupling.json must flip from green to red purely by pointing at
 * an older upstream types-root — that is the whole point of multi-version
 * verify ("what breaks if I upgrade to X", design.md Phase 2.5), and it
 * proves the redirection actually happened instead of silently resolving
 * the locally installed packages.
 *
 * The fixture coupling.json is generated by the REAL scanner so the
 * contract under test is a genuine artifact, not a hand-written imitation.
 */

function locate(candidates: string[]): string {
  for (const candidate of candidates) {
    const path = fileURLToPath(new URL(candidate, import.meta.url))
    if (existsSync(path)) return path
  }
  assert.fail(`cannot locate payload file (tried ${candidates.join(', ')})`)
}

const ANALYZE = locate(['../../scripts/analyze-dsh-coupling.mjs'])
const VERIFY = locate(['../../scripts/verify-coupling.mjs'])

const DTS_V2 = 'export interface AgentHandle { id: string; name: string }\n'
const DTS_V1 = 'export interface AgentHandle { id: string }\n'

function writePackage(dir: string, name: string, version: string, dts: string): void {
  mkdirSync(dir, { recursive: true })
  writeFileSync(join(dir, 'package.json'), `${JSON.stringify({ name, version, types: './index.d.ts', main: './index.js' }, null, 2)}\n`)
  writeFileSync(join(dir, 'index.d.ts'), dts)
}

/** A plugin repository with dsh-foo@2.0.0 installed and a real scanned coupling.json.
 *  The field surface uses the shape real plugin repos use: reads on a
 *  type-annotated parameter attributed to the package's .d.ts type. */
function writeRepoFixture(): string {
  const root = mkdtempSync(join(tmpdir(), 'dsh-types-root-'))
  writeFileSync(join(root, 'package.json'), `${JSON.stringify({
    name: 'fixture-types-root-consumer',
    private: true,
    type: 'module',
    devDependencies: { '@deepseek-ai/dsh-foo': '^2.0.0' },
  }, null, 2)}\n`)
  writePackage(join(root, 'node_modules', '@deepseek-ai', 'dsh-foo'), '@deepseek-ai/dsh-foo', '2.0.0', DTS_V2)
  mkdirSync(join(root, 'src'), { recursive: true })
  writeFileSync(join(root, 'src', 'index.ts'),
    "import type { AgentHandle } from '@deepseek-ai/dsh-foo'\n"
    + 'export function render(handle: AgentHandle): string {\n  return handle.id + handle.name\n}\n')
  const scanned = spawnSync(process.execPath, [ANALYZE, '--write'], {
    encoding: 'utf8', timeout: 60_000, cwd: root, env: { ...process.env, DSH_SEAM_ROOT: root },
  })
  assert.equal(scanned.status, 0, `scanner failed:\n${scanned.stdout}\n${scanned.stderr}`)
  assert.ok(existsSync(join(root, 'coupling.json')), 'scanner produced coupling.json')
  return root
}

function runVerify(root: string, args: string[]): { status: number | null; output: string } {
  const result = spawnSync(process.execPath, [VERIFY, ...args], {
    encoding: 'utf8', timeout: 120_000, cwd: root, env: { ...process.env, DSH_SEAM_ROOT: root },
  })
  return { status: result.status, output: `${result.stdout}\n${result.stderr}` }
}

test('control: the fixture verifies green against its installed packages', () => {
  const root = writeRepoFixture()
  try {
    const { status, output } = runVerify(root, ['coupling.json'])
    assert.equal(status, 0, output)
    assert.match(output, /2\/2 probes compile clean/, output)
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
})

test('--types-root pointing at the same version stays green and names it', () => {
  const root = writeRepoFixture()
  const typesRoot = mkdtempSync(join(tmpdir(), 'dsh-types-good-'))
  try {
    writePackage(join(typesRoot, '@deepseek-ai', 'dsh-foo'), '@deepseek-ai/dsh-foo', '2.0.0', DTS_V2)
    const { status, output } = runVerify(root, ['coupling.json', '--types-root', typesRoot])
    assert.equal(status, 0, output)
    assert.match(output, /2\/2 probes compile clean/, output)
    assert.match(output, /types-root: @deepseek-ai\/dsh-foo@2\.0\.0/, 'the report names the version under test')
  } finally {
    rmSync(root, { recursive: true, force: true })
    rmSync(typesRoot, { recursive: true, force: true })
  }
})

test('--types-root pointing at an older upstream flips the anchored field red', () => {
  const root = writeRepoFixture()
  const typesRoot = mkdtempSync(join(tmpdir(), 'dsh-types-old-'))
  try {
    // v1.0.0 dropped `name` from Agent: the anchored agent.name probe must fail.
    writePackage(join(typesRoot, '@deepseek-ai', 'dsh-foo'), '@deepseek-ai/dsh-foo', '1.0.0', DTS_V1)
    const { status, output } = runVerify(root, ['coupling.json', '--types-root', typesRoot])
    assert.notEqual(status, 0, 'the drift case must fail')
    assert.match(output, /1\/2 probes compile clean/, output)
    assert.match(output, /types-root: @deepseek-ai\/dsh-foo@1\.0\.0/, output)
    assert.match(output, /name/, 'the report names the broken surface')
    // Redundant guard: without the flag the same repository is green (see the
    // control test), so a red here means the redirection really took effect.
    const local = runVerify(root, ['coupling.json'])
    assert.equal(local.status, 0, local.output)
  } finally {
    rmSync(root, { recursive: true, force: true })
    rmSync(typesRoot, { recursive: true, force: true })
  }
})

test('--types-root without @deepseek-ai packages is an explicit error, not a silent skip', () => {
  const root = writeRepoFixture()
  const typesRoot = mkdtempSync(join(tmpdir(), 'dsh-types-empty-'))
  try {
    const { status, output } = runVerify(root, ['coupling.json', '--types-root', typesRoot])
    assert.notEqual(status, 0, 'an empty types-root must fail loudly')
    assert.match(output, /types-root .*no @deepseek-ai packages/, output)
    assert.doesNotMatch(output, /0\/0 probes compile clean/, 'must not degrade into the no-packages skip path')
  } finally {
    rmSync(root, { recursive: true, force: true })
    rmSync(typesRoot, { recursive: true, force: true })
  }
})
